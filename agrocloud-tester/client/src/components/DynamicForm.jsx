import React, { useState, useEffect } from 'react';
import { api } from '../api.js';
import Alert from './Alert.jsx';
import { RefreshCw, CheckCircle2 } from 'lucide-react';

export default function DynamicForm({ tableName, onSuccess, onCancel }) {
  const [columns, setColumns] = useState([]);
  const [fkOptions, setFkOptions] = useState({});
  const [formData, setFormData] = useState({});
  const [loading, setLoading] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState(null);
  const [successMsg, setSuccessMsg] = useState(null);

  useEffect(() => {
    if (tableName) {
      loadMetaAndOptions(tableName);
    }
  }, [tableName]);

  async function loadMetaAndOptions(tbl) {
    setLoading(true);
    setErrorMsg(null);
    setSuccessMsg(null);
    setFormData({});
    try {
      // 1. Obtener metadatos de columnas
      const meta = await api.getTableMeta(tbl);
      const cols = meta.columns || [];
      setColumns(cols);

      // 2. Para cada FK, cargar opciones de la tabla referenciada
      const fkPromises = [];
      const fkCols = cols.filter(c => c.fk && c.fk.foreignTable);

      for (const col of fkCols) {
        fkPromises.push(
          api.getTableOptions(col.fk.foreignTable)
            .then(options => ({ colName: col.name, options }))
            .catch(() => ({ colName: col.name, options: [] }))
        );
      }

      const results = await Promise.all(fkPromises);
      const optionsMap = {};
      results.forEach(item => {
        optionsMap[item.colName] = item.options;
      });
      setFkOptions(optionsMap);

      // 3. Inicializar valores por defecto vacíos para campos requeridos
      const initial = {};
      cols.forEach(col => {
        if (!col.isAutoGenerated) {
          if (col.dataType === 'boolean') {
            initial[col.name] = false;
          } else {
            initial[col.name] = '';
          }
        }
      });
      setFormData(initial);
    } catch (err) {
      setErrorMsg(`Error cargando metadatos de ${tbl}: ${err.message}`);
    } finally {
      setLoading(false);
    }
  }

  const handleInputChange = (colName, value, dataType) => {
    setFormData(prev => ({
      ...prev,
      [colName]: value
    }));
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setSubmitting(true);
    setErrorMsg(null);
    setSuccessMsg(null);

    // Preparar payload filtrando campos vacíos que no sean requeridos
    const payload = {};
    columns.forEach(col => {
      if (col.isAutoGenerated) return;

      const rawVal = formData[col.name];
      if (col.dataType === 'boolean') {
        payload[col.name] = Boolean(rawVal);
      } else if (rawVal !== undefined && rawVal !== '') {
        // Conversión según tipo
        if (['integer', 'smallint', 'bigint'].includes(col.dataType)) {
          payload[col.name] = parseInt(rawVal, 10);
        } else if (['numeric', 'decimal', 'real', 'double precision'].includes(col.dataType)) {
          payload[col.name] = parseFloat(rawVal);
        } else {
          payload[col.name] = rawVal;
        }
      }
    });

    try {
      const res = await api.insertTableRow(tableName, payload);
      const insertedId = res.row?.id || '(sin id)';
      setSuccessMsg(`Registro insertado con éxito con ID: ${insertedId}`);

      // Limpiar formulario
      const cleared = {};
      columns.forEach(col => {
        if (!col.isAutoGenerated) {
          cleared[col.name] = col.dataType === 'boolean' ? false : '';
        }
      });
      setFormData(cleared);

      if (onSuccess) onSuccess(res.row, tableName);
    } catch (err) {
      setErrorMsg(err.message || 'Error al guardar el registro');
    } finally {
      setSubmitting(false);
    }
  };

  // Filtrar columnas a mostrar: omitir 'id' y auto-generados con defaults
  const editableCols = columns.filter(col => !col.isAutoGenerated);

  if (loading) {
    return (
      <div className="p-8 flex items-center justify-center gap-2 text-[#9ca3af]">
        <RefreshCw className="w-5 h-5 animate-spin text-[#16a34a]" />
        <span className="text-sm">Analizando estructura de {tableName}...</span>
      </div>
    );
  }

  return (
    <form onSubmit={handleSubmit} className="space-y-4">
      {errorMsg && <Alert type="error" message={errorMsg} />}
      {successMsg && <Alert type="success" message={successMsg} />}

      {editableCols.length === 0 ? (
        <div className="text-xs text-[#9ca3af] py-2">
          No hay columnas editables detectadas. Se usarán valores por defecto.
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {editableCols.map(col => {
            const isRequired = !col.isNullable && col.defaultValue === null;
            const hasFK = col.fk && fkOptions[col.name];

            // Renderizar selector de FK
            if (hasFK) {
              const options = fkOptions[col.name] || [];
              return (
                <div key={col.name} className="md:col-span-2">
                  <label className="block text-xs font-medium text-[#9ca3af] mb-1">
                    {col.name} {isRequired && <span className="text-[#dc2626]">*</span>}
                    <span className="text-[11px] text-[#16a34a] font-mono ml-2">
                      (FK &rarr; {col.fk.foreignTable}.{col.fk.foreignColumn})
                    </span>
                  </label>
                  <select
                    value={formData[col.name] || ''}
                    onChange={(e) => handleInputChange(col.name, e.target.value, col.dataType)}
                    required={isRequired}
                    className="w-full h-9 bg-[#0f1115] border border-[#262b36] focus:border-[#16a34a] outline-none px-3 text-sm rounded-[4px] text-[#e5e7eb] font-mono transition-colors duration-150"
                  >
                    <option value="">-- Seleccionar de {col.fk.foreignTable} --</option>
                    {options.map(opt => (
                      <option key={opt.value} value={opt.value}>
                        {opt.label}
                      </option>
                    ))}
                  </select>
                  {options.length === 0 && (
                    <span className="text-[11px] text-[#d97706] mt-1 block">
                      Aviso: La tabla {col.fk.foreignTable} no tiene registros para seleccionar.
                    </span>
                  )}
                </div>
              );
            }

            // Renderizar Booleano
            if (col.dataType === 'boolean') {
              return (
                <div key={col.name} className="flex items-center gap-2 pt-5">
                  <input
                    type="checkbox"
                    id={`field-${col.name}`}
                    checked={Boolean(formData[col.name])}
                    onChange={(e) => handleInputChange(col.name, e.target.checked, col.dataType)}
                    className="w-4 h-4 bg-[#0f1115] border border-[#262b36] rounded text-[#16a34a] focus:ring-0 cursor-pointer"
                  />
                  <label htmlFor={`field-${col.name}`} className="text-xs font-medium text-[#e5e7eb] cursor-pointer">
                    {col.name} {isRequired && <span className="text-[#dc2626]">*</span>}
                  </label>
                </div>
              );
            }

            // Renderizar Numérico
            const isNumeric = ['integer', 'smallint', 'bigint', 'numeric', 'decimal', 'real', 'double precision'].includes(col.dataType);
            if (isNumeric) {
              return (
                <div key={col.name}>
                  <label className="block text-xs font-medium text-[#9ca3af] mb-1">
                    {col.name} {isRequired && <span className="text-[#dc2626]">*</span>}
                    <span className="text-[10px] text-[#9ca3af] font-mono ml-1">({col.dataType})</span>
                  </label>
                  <input
                    type="number"
                    step={col.dataType.includes('int') ? '1' : 'any'}
                    value={formData[col.name] !== undefined ? formData[col.name] : ''}
                    onChange={(e) => handleInputChange(col.name, e.target.value, col.dataType)}
                    required={isRequired}
                    placeholder={`Ingrese ${col.name}`}
                    className="w-full h-9 bg-[#0f1115] border border-[#262b36] focus:border-[#16a34a] outline-none px-3 text-sm rounded-[4px] text-[#e5e7eb] font-mono transition-colors duration-150"
                  />
                </div>
              );
            }

            // Renderizar Fecha / Timestamp
            if (col.dataType === 'date') {
              return (
                <div key={col.name}>
                  <label className="block text-xs font-medium text-[#9ca3af] mb-1">
                    {col.name} {isRequired && <span className="text-[#dc2626]">*</span>}
                    <span className="text-[10px] text-[#9ca3af] font-mono ml-1">(date)</span>
                  </label>
                  <input
                    type="date"
                    value={formData[col.name] || ''}
                    onChange={(e) => handleInputChange(col.name, e.target.value, col.dataType)}
                    required={isRequired}
                    className="w-full h-9 bg-[#0f1115] border border-[#262b36] focus:border-[#16a34a] outline-none px-3 text-sm rounded-[4px] text-[#e5e7eb] font-mono transition-colors duration-150"
                  />
                </div>
              );
            }

            if (col.dataType.includes('timestamp')) {
              return (
                <div key={col.name}>
                  <label className="block text-xs font-medium text-[#9ca3af] mb-1">
                    {col.name} {isRequired && <span className="text-[#dc2626]">*</span>}
                    <span className="text-[10px] text-[#9ca3af] font-mono ml-1">(timestamp)</span>
                  </label>
                  <input
                    type="datetime-local"
                    value={formData[col.name] || ''}
                    onChange={(e) => handleInputChange(col.name, e.target.value, col.dataType)}
                    required={isRequired}
                    className="w-full h-9 bg-[#0f1115] border border-[#262b36] focus:border-[#16a34a] outline-none px-3 text-sm rounded-[4px] text-[#e5e7eb] font-mono transition-colors duration-150"
                  />
                </div>
              );
            }

            // Resto: Texto plano
            return (
              <div key={col.name}>
                <label className="block text-xs font-medium text-[#9ca3af] mb-1">
                  {col.name} {isRequired && <span className="text-[#dc2626]">*</span>}
                  <span className="text-[10px] text-[#9ca3af] font-mono ml-1">({col.dataType})</span>
                </label>
                <input
                  type="text"
                  value={formData[col.name] || ''}
                  onChange={(e) => handleInputChange(col.name, e.target.value, col.dataType)}
                  required={isRequired}
                  placeholder={`Ingrese ${col.name}`}
                  className="w-full h-9 bg-[#0f1115] border border-[#262b36] focus:border-[#16a34a] outline-none px-3 text-sm rounded-[4px] text-[#e5e7eb] transition-colors duration-150"
                />
              </div>
            );
          })}
        </div>
      )}

      <div className="pt-3 border-t border-[#262b36] flex items-center justify-end gap-2">
        {onCancel && (
          <button
            type="button"
            onClick={onCancel}
            className="h-9 px-4 text-sm font-medium text-[#e5e7eb] bg-transparent border border-[#262b36] rounded-[6px] hover:bg-[#1b1f28] transition-colors duration-150"
          >
            Cancelar
          </button>
        )}
        <button
          type="submit"
          disabled={submitting}
          className="h-9 px-4 text-sm font-medium text-white bg-[#16a34a] hover:bg-[#15803d] rounded-[6px] transition-colors duration-150 flex items-center gap-2"
        >
          {submitting ? <RefreshCw className="w-4 h-4 animate-spin" /> : <CheckCircle2 className="w-4 h-4" />}
          <span>Guardar en {tableName}</span>
        </button>
      </div>
    </form>
  );
}
